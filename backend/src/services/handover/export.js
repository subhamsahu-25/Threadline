function iso(value) {
  if (!value) return null;
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? null : date.toISOString();
}

function quoteBlock(quote) {
  return String(quote || '')
    .split(/\r?\n/)
    .map((line) => `> ${line}`)
    .join('\n');
}

function itemSection(item) {
  const lines = [];
  lines.push(`### ${item.statement}`);
  lines.push('');
  const facts = [];
  facts.push(`Type: ${item.type}`);
  facts.push(`Status: ${item.status || item.state || 'unknown'}`);
  if (item.ownerName) facts.push(`Owner: ${item.ownerName}`);
  if (item.dueAt) facts.push(`Due: ${iso(item.dueAt)?.slice(0, 10)}`);
  if (item.origin === 'person_confirmed') {
    facts.push(
      `Person-confirmed by ${item.confirmedByName || 'a teammate'}${
        item.confirmedAt ? ` on ${iso(item.confirmedAt)?.slice(0, 10)}` : ''
      }`,
    );
  }
  if (item.decision === 'edited') facts.push('Wording reviewed by the project team');
  lines.push(facts.map((fact) => `- ${fact}`).join('\n'));

  for (const citation of item.citations || []) {
    lines.push('');
    lines.push(
      `**Evidence:** ${citation.sourceName || 'Source'}${
        citation.docTitle ? ` · ${citation.docTitle}` : ''
      } (${citation.validation || 'unverified'})`,
    );
    if (citation.quote) {
      lines.push('');
      lines.push(quoteBlock(citation.quote));
    }
  }
  if (item.resolutionNote) {
    lines.push('');
    lines.push(`**Closure note:** ${item.resolutionNote}`);
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * Renders the same permission-filtered view the reader sees on screen. The
 * function never reads the database, so an export cannot include an item the
 * viewer was not allowed to open.
 */
export function renderHandoverMarkdown({ handover, projectName, viewer }) {
  const snapshot = handover.snapshot || {};
  const fields = [
    `**Project:** ${snapshot.projectName || projectName || 'Project'}`,
    `**Recipient:** ${handover.recipientSnapshot?.name || 'Recipient'}`,
    `**Status:** ${handover.status} · version ${handover.version}`,
    `**Prepared by:** ${handover.createdBySnapshot?.name || 'Project team'}`,
    handover.approvedAt
      ? `**Approved:** ${iso(handover.approvedAt)} by ${
          handover.approvedBySnapshot?.name || 'a project lead'
        }`
      : null,
    handover.acknowledgedAt ? `**Acknowledged:** ${iso(handover.acknowledgedAt)}` : null,
    `**Exported:** ${new Date().toISOString()}`,
    `**View:** ${viewer === 'reviewer' ? 'reviewer copy' : 'recipient copy'}`,
  ].filter(Boolean);

  const lines = [
    `# Handover for ${handover.recipientSnapshot?.name || 'the recipient'}`,
    '',
    ...fields,
    '',
    '> This export was produced from the same permission-filtered view shown in the product. Items the reader is not allowed to see are not included.',
    '',
  ];

  if (snapshot.generatedSummary) {
    lines.push('## Summary', '', snapshot.generatedSummary, '');
  }

  const items = handover.items || [];
  lines.push(`## Items (${items.length})`, '');
  if (items.length === 0) {
    lines.push('No approved items were included in this view.', '');
  }
  for (const item of items) lines.push(itemSection(item));

  if (viewer === 'reviewer' && handover.withheld?.total > 0) {
    lines.push('## Withheld from this view', '');
    const reasons = handover.withheld.byReason || {};
    lines.push(
      `- ${handover.withheld.total} item(s) withheld: permissions ${
        reasons.permissions || 0
      }, author access ${reasons.author_permissions || 0}, template ${
        reasons.template || 0
      }, unverified evidence ${reasons.unverified || 0}. Details are intentionally omitted.`,
      '',
    );
  }

  if (handover.alerts?.length > 0) {
    lines.push('## Alerts', '');
    for (const alert of handover.alerts) {
      lines.push(`- **${alert.severity || 'info'}:** ${alert.message}`);
    }
    lines.push('');
  }

  if (handover.recommendations?.length > 0) {
    lines.push('## Suggested next actions (inferred, not extracted facts)', '');
    for (const action of handover.recommendations) {
      lines.push(`- **${action.priority || 'medium'}:** ${action.title}`);
      if (action.reason) lines.push(`  - ${action.reason}`);
    }
    lines.push('');
  }

  lines.push(
    '---',
    '',
    `Generated by Threadline for ${snapshot.projectKey || projectName || 'this project'}. Ask the project team if anything here is unclear; the share link accepts notes from the recipient.`,
    '',
  );

  return lines.join('\n');
}
